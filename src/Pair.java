public class Pair {
    private long first;
    private double second;

    public Pair(long first, double second) {
        this.first = first;
        this.second = second;
    }

    public long getFirst() {
        return first;
    }

    public double getSecond() {
        return second;
    }

    public void setSecond(double second) {
        this.second = second;
    }
}
